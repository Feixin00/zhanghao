      updateCrawl(id, values) {
        const columnMap = {
          enabled: "crawl_enabled",
          autoGenerateDrafts: "auto_generate_drafts",
          intervalHours: "crawl_interval_hours",
          maxPosts: "crawl_max_posts",
          lookbackHours: "crawl_lookback_hours",
          status: "crawl_status",
          lastRunAt: "crawl_last_run_at",
          nextRunAt: "crawl_next_run_at",
          lastMessage: "crawl_last_message",
        };
        const entries = Object.entries(values).filter(([key]) => columnMap[key]);
        if (!entries.length) return Boolean(getAccount(id));
        const assignments = entries.map(([key]) => `${columnMap[key]} = @${key}`).join(", ");
        const normalized = { id };
        const booleanKeys = new Set(["enabled", "autoGenerateDrafts"]);
        for (const [key, value] of entries) normalized[key] = booleanKeys.has(key) ? Number(Boolean(value)) : value;
        return database.prepare(`UPDATE accounts SET ${assignments} WHERE id = @id`).run(normalized).changes > 0;
      },
