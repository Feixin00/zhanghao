function normalizeLoginState(payload, adapter) {
  const source = payload?.state;
  const cookies = Array.isArray(source) ? source : source?.cookies;

  if (!Array.isArray(cookies) || cookies.length === 0) {
    throw new Error("状态文件中没有可用的 Cookie");
  }

  const normalizedCookies = cookies.map((cookie, index) => {
    if (!cookie || typeof cookie !== "object" || Array.isArray(cookie)) {
      throw new Error(`第 ${index + 1} 个 Cookie 格式不正确`);
    }

    const name = typeof cookie.name === "string" ? cookie.name.trim() : "";
    const hasStringValue = typeof cookie.value === "string";
    const value = hasStringValue ? cookie.value : "";
    const domain = typeof cookie.domain === "string" ? cookie.domain.trim().toLowerCase() : "";
    const normalizedDomain = domain.replace(/^\./, "");

    if (!name || !hasStringValue || !domain) {
      throw new Error(`第 ${index + 1} 个 Cookie 缺少 name、value 或 domain`);
    }
    const allowed = adapter.cookieDomains.some(
      (allowedDomain) => normalizedDomain === allowedDomain || normalizedDomain.endsWith(`.${allowedDomain}`),
    );
    if (!allowed) {
      throw new Error(`状态文件包含非${adapter.label}域名的 Cookie，请上传该平台导出的状态文件`);
    }

    const normalized = {};
    for (const field of COOKIE_FIELDS) {
      if (cookie[field] !== undefined) normalized[field] = cookie[field];
    }
    normalized.name = name;
    normalized.value = value;
    normalized.domain = domain;
    return normalized;
  });

  return {
    version: Number(source?.version) || 1,
    exported_at: typeof source?.exported_at === "string"
      ? source.exported_at
      : new Date().toISOString(),
    cookies: normalizedCookies,
  };
}

function validateCrawlPayload(payload) {
  const settings = {
    enabled: payload?.enabled === true,
    autoGenerateDrafts: payload?.enabled === true && payload?.autoGenerateDrafts === true,
    intervalHours: Number(payload?.intervalHours),
    maxPosts: Number(payload?.maxPosts),
    lookbackHours: Number(payload?.lookbackHours),
  };
  const errors = {};

  if (!Number.isFinite(settings.intervalHours) || settings.intervalHours < 0.01 || settings.intervalHours > 720) {
    errors.intervalHours = "抓取周期需为 0.01～720 小时的数字";
  }
  if (!Number.isInteger(settings.maxPosts) || settings.maxPosts < 1 || settings.maxPosts > 100) {
    errors.maxPosts = "每次扫描条数需为 1～100 的整数";
  }
  if (!Number.isInteger(settings.lookbackHours) || settings.lookbackHours < 1 || settings.lookbackHours > 87600) {
    errors.lookbackHours = "时间范围需为 1～87600 小时的整数";
  }

  return { settings, errors };
}

