function serializeDate(value) {
  return value instanceof Date ? value.toISOString() : value || null;
}

function parseXSessionIdentity(output) {
  const line = String(output || "")
    .split(/\r?\n/)
    .find((item) => item.startsWith(X_SESSION_IDENTITY_PREFIX));
  if (!line) return "";
  try {
    const payload = JSON.parse(line.slice(X_SESSION_IDENTITY_PREFIX.length));
    return typeof payload?.handle === "string" ? payload.handle.trim().replace(/^@/, "") : "";
  } catch {
    return "";
  }
}

