import { rm } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import path from "node:path";
import { shouldAutoGenerateCrawlResults } from "../server/crawler-service.js";
import { openSqliteStore } from "../server/sqlite-store.js";

const databasePath = path.resolve(import.meta.dirname, `../data/auto-generation-settings-${randomUUID()}.sqlite`);

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

await rm(databasePath, { force: true });
await rm(`${databasePath}-wal`, { force: true });
await rm(`${databasePath}-shm`, { force: true });

let store = openSqliteStore(databasePath);
try {
  const timestamp = new Date().toISOString();
  const account = store.accounts.insert({
    name: "自动生成测试账号",
    url: "https://x.com/auto_test",
    type: "测试类型",
    platform: "X",
    region: "国外",
    details: "自动抓取后生成稿件",
    promptId: null,
    createdAt: timestamp,
    updatedAt: timestamp,
  });

  const saved = store.accounts.saveCrawlSettings(account._id, {
    enabled: true,
    autoGenerateDrafts: true,
    intervalHours: 0.01,
    maxPosts: 10,
    lookbackHours: 24,
  }, new Date(Date.now() + 36_000).toISOString(), timestamp);

  assert(store.schemaVersion === 22, "数据库结构没有升级到 v22");
  assert(saved.crawl.enabled === true, "自动抓取设置没有保存");
  assert(saved.crawl.autoGenerateDrafts === true, "自动生成稿件设置没有保存");
  assert(
    shouldAutoGenerateCrawlResults({ trigger: "scheduled" }, saved.crawl, ["new-content"]),
    "定时抓取新增内容没有进入自动生成条件",
  );
  assert(
    !shouldAutoGenerateCrawlResults({ trigger: "manual" }, saved.crawl, ["new-content"]),
    "手动抓取不应触发自动生成",
  );
  assert(
    !shouldAutoGenerateCrawlResults({ trigger: "scheduled" }, saved.crawl, []),
    "没有新增内容时不应触发自动生成",
  );

  const insertLegacyContent = store.database.prepare(`
    INSERT INTO contents (
      id, account_id, account_name, account_region, platform, platform_post_id,
      source_url, status, created_at, updated_at
    ) VALUES (?, ?, '自动生成测试账号', '国外', 'X', ?, ?, ?, ?, ?)
  `);
  ["未处理", "待改写", "已使用", "已归档"].forEach((status, index) => {
    insertLegacyContent.run(
      `legacy-content-${index}`,
      account._id,
      `legacy-post-${index}`,
      `https://x.com/auto_test/status/${index}`,
      status,
      timestamp,
      timestamp,
    );
  });
  store.database.pragma("user_version = 13");
  store.close();
  store = openSqliteStore(databasePath);
  const migratedStatuses = store.database.prepare(`
    SELECT id, status FROM contents ORDER BY id ASC
  `).all();
  assert(
    migratedStatuses.every((item) => ["待处理", "已处理"].includes(item.status)),
    "旧内容状态没有迁移为待处理或已处理",
  );
  assert(migratedStatuses[0].status === "待处理", "旧未处理状态迁移错误");
  assert(migratedStatuses.slice(1).every((item) => item.status === "已处理"), "旧已进入处理流程的状态迁移错误");

  store.close();
  store = openSqliteStore(databasePath);
  assert(store.schemaVersion === 22, "v22 数据库无法由当前程序重新打开");

  console.log(JSON.stringify({
    ok: true,
    schemaVersion: store.schemaVersion,
    autoGenerateDrafts: saved.crawl.autoGenerateDrafts,
    scheduledOnly: true,
    migratedStatuses: migratedStatuses.map((item) => item.status),
  }));
} finally {
  store?.close();
  await rm(databasePath, { force: true });
  await rm(`${databasePath}-wal`, { force: true });
  await rm(`${databasePath}-shm`, { force: true });
}
